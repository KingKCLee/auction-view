/**
 * 항목코드에 이름을 붙인다.
 * @returns {{name:string,basis:string}|null} 확정하지 못한 코드는 null - 코드 그대로 보여 준다.
 */
const labelOf = (code) => LABELS[String(code || '')] || null;

/** 요항 배열에 이름을 붙여 돌려준다. 원래 값은 건드리지 않는다. */
function withLabels(points) {
  if (!Array.isArray(points)) return [];
  return points.map((p) => {
    const l = labelOf(p && p.itemCode);
    return l ? { ...p, label: l.name, labelBasis: l.basis } : { ...p };
  });
}

module.exports = { LABELS, labelOf, withLabels };
